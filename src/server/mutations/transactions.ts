import { and, eq, inArray } from "drizzle-orm"

import { DEMO_USER_ID, getDb } from "@/server/db"
import { accounts, cards, transactions } from "@/server/db/schema"
import { displayDate } from "@/server/db/format"
import type { FullTransaction } from "@/lib/types"

export type NewTransactionInput = {
  merchant: string
  amount: number // always positive; sign is derived from `type`
  type: "expense" | "income"
  category: string
  date: string // ISO yyyy-MM-dd
  /** Funding account whose balance this transaction affects. Null for a
   * credit card purchase — credit spend doesn't debit any account; it's
   * netted into the card's derived balance owed instead (see getCards() in
   * @/server/queries/cards). Must be null when cardId resolves to a
   * product === "credit" card, and non-null otherwise. */
  accountId: number | null
  /** Card the purchase was made with. For non-credit cards this is
   * display-only and doesn't affect account balance. */
  cardId?: number
  status: "completed" | "pending" | "failed"
  notes?: string
}

/** Synthesizes an id in the same shape as the seeded ledger (e.g. "TXN_847291"). */
export function generateTransactionId(): string {
  return `TXN_${Math.floor(100000 + Math.random() * 900000)}`
}

/** Records a manually-entered transaction and keeps the linked account's
 * balance in sync — an expense debits it, income credits it — atomically,
 * mirroring createTransfer() in @/server/mutations/transfers. When cardId
 * resolves to a credit card, accountId must be null: credit spend is netted
 * into the card's derived balance owed (see getCards() in
 * @/server/queries/cards) instead of debiting a funding account — applying
 * it to an account here as well would double-count it once the bill is
 * paid via createCardPayment. */
export async function createTransaction(input: NewTransactionInput): Promise<FullTransaction> {
  const db = getDb()

  // Seeded rows store expenses negative and income positive (see
  // src/server/db/fixtures.ts) — normalize once so the same signed value
  // is both the stored amount and the balance delta below.
  const signed = input.type === "expense" ? -Math.abs(input.amount) : Math.abs(input.amount)

  const { row, cardLast4 } = db.transaction((tx) => {
    let cardId: number | null = null
    let cardLast4: string | undefined
    if (input.cardId != null) {
      const card = tx.select().from(cards).where(eq(cards.id, input.cardId)).get()
      if (!card || card.userId !== DEMO_USER_ID) {
        throw new Error(`Card ${input.cardId} not found`)
      }
      cardId = card.id
      cardLast4 = card.last4
      if (card.product === "credit" && input.accountId != null) {
        throw new Error(`${card.name} is a credit card — it has no funding account`)
      }
      if (card.product !== "credit" && input.accountId == null) {
        throw new Error("accountId is required for a non-credit card transaction")
      }
    } else if (input.accountId == null) {
      throw new Error("accountId is required")
    }

    const account =
      input.accountId != null
        ? tx.select().from(accounts).where(eq(accounts.id, input.accountId)).get()
        : null
    if (input.accountId != null && !account) {
      throw new Error(`Account ${input.accountId} not found`)
    }

    const [inserted] = tx
      .insert(transactions)
      .values({
        userId: DEMO_USER_ID,
        accountId: input.accountId,
        cardId,
        merchant: input.merchant,
        transactionId: generateTransactionId(),
        amount: signed,
        date: input.date,
        logo: "",
        category: input.category,
        status: input.status,
        type: input.type,
        notes: input.notes,
      })
      .returning()
      .all()

    if (account) {
      tx.update(accounts)
        .set({ balance: Math.round((account.balance + signed) * 100) / 100 })
        .where(eq(accounts.id, account.id))
        .run()
    }

    return { row: inserted, cardLast4 }
  })

  return {
    id: String(row.id),
    merchant: row.merchant,
    transactionId: row.transactionId,
    amount: row.amount,
    date: displayDate(row.date),
    logo: row.logo,
    category: row.category,
    status: row.status,
    type: row.type,
    notes: row.notes ?? undefined,
    merchantInfo: row.merchantInfo ?? undefined,
    cardLast4,
    isTransfer: false,
  }
}

export type DeleteTransactionsResult = { deleted: number; skipped: number }

/** Deletes ledger rows and reverses each one's effect on its account balance
 * — the inverse of createTransaction() above. Rows generated by an internal
 * transfer, or the funding-account leg of a card payment, are skipped: both
 * are auto-generated by their own mutation (createInternalTransfer in
 * @/server/mutations/transfers, createCardPayment in
 * @/server/mutations/card-payments) which is where they should be reversed
 * from instead, keeping every side effect of undoing them in one place. */
export async function deleteTransactions(ids: number[]): Promise<DeleteTransactionsResult> {
  const db = getDb()

  return db.transaction((tx) => {
    if (ids.length === 0) return { deleted: 0, skipped: 0 }

    const rows = tx
      .select()
      .from(transactions)
      .where(and(eq(transactions.userId, DEMO_USER_ID), inArray(transactions.id, ids)))
      .all()

    const deletable = rows.filter((r) => r.transferId == null && r.cardPaymentId == null)
    const skipped = rows.length - deletable.length
    if (deletable.length === 0) return { deleted: 0, skipped }

    const deltaByAccount = new Map<number, number>()
    for (const row of deletable) {
      if (row.accountId == null) continue
      deltaByAccount.set(row.accountId, (deltaByAccount.get(row.accountId) ?? 0) - row.amount)
    }

    for (const [accountId, delta] of deltaByAccount) {
      const account = tx.select().from(accounts).where(eq(accounts.id, accountId)).get()
      if (!account) continue
      tx.update(accounts)
        .set({ balance: Math.round((account.balance + delta) * 100) / 100 })
        .where(eq(accounts.id, accountId))
        .run()
    }

    tx.delete(transactions)
      .where(inArray(transactions.id, deletable.map((r) => r.id)))
      .run()

    return { deleted: deletable.length, skipped }
  })
}
